/**
 * Assemble the browser bundle (`lib/client.js`) from its sources.
 *
 * The web frontend loads plugin clients as factory-form CJS: a single file that
 * calls `window.__ModuleLoader__.load({ id, factory })`, where the factory
 * receives the host's shared-module `require` (`react`, the dsh client packages).
 * This script inlines the pure helpers (`lib/client-models.js`) and the app
 * composition root (`lib/client-app.js`) by serializing their function sources,
 * so no bundler is involved and both sources stay the single points of truth.
 *
 * Run: node scripts/build-client.mjs
 * `npm test` rebuilds the bundle and fails when the committed file is stale.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import * as models from "../lib/client-models.js";
import { createClientApp, createOperations } from "../lib/client-app.js";

// The client-module manifest keys every plugin by its package name, and the
// module system materializes factories under that id, so the wrapper id must
// match it exactly.
const pkgName = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8")).name;

const HELPER_NAMES = [
  "SETTINGS_NS",
  "ACCOUNT_ROUTE_PREFIX",
  "CATALOG_PREFIX",
  "CATALOG_REFRESH_SUFFIX",
  // The account-route id contract (lib/credentials.js re-exports it for the host
  // half). isAccountRoute references ACCOUNT_ROUTE_PREFIX, so both are inlined.
  "isAccountRoute",
  "modelsPathFor",
  // The command text contract (the tags and row prefixes lib/commands.js and
  // lib/usage.js emit and the parsers match), plus the window labels the composer
  // indicator keys its bands on.
  "USAGE_TAG",
  "ACCOUNT_TAG",
  "ACCOUNT_PREFIX",
  "PLAN_PREFIX",
  "AUTH_PREFIX",
  "ORGANIZATION_PREFIX",
  "TOKEN_PREFIX",
  "NOTE_PREFIX",
  "OBSERVED_PREFIX",
  "ROUTE_PREFIX",
  "NO_USAGE_DATA",
  "EXTRA_LABEL",
  "FIVE_HOUR_LABEL",
  "normalizeRow",
  "availableModelIds",
  "setModelsOp",
  "unsetModelsOp",
  "readAccounts",
  "readMirror",
  "readModelLists",
  "readCatalog",
  "readCatalogSnapshot",
  "nonEmpty",
  "rowsDiffer",
  "popoverAlign",
  "normalizeUsageView",
  "parseUsageText",
  "parseAccountText",
  "resetDetail",
  // Not app dependencies: the app calls withoutClock (usage-card rows) and
  // resetDetail calls both. The bundle serializes each function by source, so every
  // module-level binding a helper reaches must be listed here too
  // (test/client-bundle.test.mjs evaluates the bundle to catch a miss).
  "withoutClock",
  "countdownDuration",
];

const helperSource = HELPER_NAMES.map((helperName) => {
  const value = models[helperName];
  if (value === undefined)
    throw new Error(`build-client: lib/client-models.js no longer exports ${helperName}`);
  // Functions serialize as their source. Plain values as JSON literals.
  const source = typeof value === "function" ? value.toString() : JSON.stringify(value);
  return `const ${helperName} = ${source};`;
}).join("\n");

const appSource = createClientApp.toString();
// The helper bag is derived from the app's own destructure. Inlining a name is not
// enough: the app reads it from `helpers`, and a name left out of the bag is a
// silent `undefined` at runtime that no deterministic test notices. So the bag and
// the inlined set are checked against each other at build time.
const helperBag = (() => {
  const destructure = /const\s*\{([^}]*)\}\s*=\s*helpers\b/.exec(appSource);
  if (destructure === null)
    throw new Error("build-client: createClientApp no longer destructures from `helpers`");
  const names = destructure[1]
    .split(",")
    .map((entry) => entry.split(":")[0].trim())
    .filter((name) => name.length > 0);
  const missing = names.filter((name) => !HELPER_NAMES.includes(name));
  if (missing.length > 0) {
    throw new Error(
      `build-client: createClientApp destructures ${missing.join(", ")} from helpers, but scripts/build-client.mjs does not inline them: add them to HELPER_NAMES`,
    );
  }
  return names;
})();
// createOperations is a module-level export of client-app.js (hoisted out of
// createClientApp so tests can drive it). The bundle inlines it beside its caller,
// which references it by name.
const operationsSource = createOperations.toString();
// The host's shared Tooltip primitive (the context meter's), a registered shared
// module on current hosts. The require is guarded because the module is
// host-mapped, not an npm dependency: a host build without it (or without the
// Tooltip export) must degrade to a tooltip-less trigger, not fail the whole
// client factory and take the Models-page card down with it.
const primitivesSource =
  '(() => { try { return require("@deepseek-ai/dsh-client-ui-primitives"); } catch { return undefined; } })()';

const bundle = `/* eslint-disable */
/* GENERATED by scripts/build-client.mjs. Edit lib/client-app.js and
   lib/client-models.js, then run \`npm run build:client\`. Do not edit by hand. */
/**
 * Browser half of the Claude subscription plugin: a model-list editor card on
 * the Settings → Models page, mounted through the \`settings.models.footer\`
 * slot. Usage and account cards render \`/claude-usage\` and
 * \`/claude-account\` results through the \`conversation.chat.commandview\`
 * slot (keyed by the command name). And a 5-hour usage mark sits before the model
 * selector (\`conversation.input.right\`),
 * depleted by utilization, fed from the usage card's localStorage cache and
 * from the host's published usage snapshots (the self-refresh pulls). The
 * models card reads and writes the
 * volatile \`provider\` section of this plugin's settings document, the same
 * section the host adapter serves, so an edit reaches the next model listing
 * without a restart.
 *
 * The official Models page editor card is reserved for the first-party
 * \`llm-deepseek\` / \`llm-pi-ai\` namespaces (any other configurable provider
 * renders a stub), which is why this plugin ships its own card.
 *
 * Loaded by the web frontend's module loader as a factory-form CJS bundle. The
 * host maps shared modules (\`react\`, the dsh client packages) into \`require\`.
 */
window.__ModuleLoader__.load({
	id: ${JSON.stringify(pkgName)},
	factory: (require) => {
		const React = require("react");
		// Both are host-mapped, not npm dependencies, and a host may leave react-dom
		// unmapped: a missing one must degrade (the app already tolerates ReactDOM ===
		// undefined), never take the whole client factory and every slot entry down.
		const ReactDOM = (() => { try { return require("react-dom"); } catch { return undefined; } })();
${helperSource}
		const createOperations = ${operationsSource};
		const primitives = ${primitivesSource};
		return (${appSource})({ React, ReactDOM, pluginName: ${JSON.stringify(pkgName)}, helpers: { ${helperBag.join(", ")} }, primitives });
	},
});
`;

const target = new URL("../lib/client.js", import.meta.url);
const existing = existsSync(target) ? readFileSync(target, "utf8") : undefined;
writeFileSync(target, bundle);
if (existing !== undefined && existing !== bundle) {
  console.log("client bundle rebuilt (lib/client.js changed)");
} else {
  console.log("client bundle is up to date");
}
